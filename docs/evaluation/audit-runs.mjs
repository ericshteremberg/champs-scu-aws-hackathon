// Offline audit of saved synthetic runs. No network, model calls, or workspace writes.
// Usage: node docs/evaluation/audit-runs.mjs [directory-of-run-json-files]
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const directory = process.argv[2] || 'docs/evaluation/runs';
const expected = { 'ATM-1042': 'supported', 'ATM-1043': 'mixed', 'ATM-1044': 'insufficient' };
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const rows = [];
const packet = [
  '# Saved-run source review packet', '',
  'Generated by `node docs/evaluation/audit-runs.mjs`. Raw runs are unchanged.', '',
  'All records are fictional. This packet places every finding beside its cited records and includes the full draft, summary, recommendation, gaps, and source appendix. It does not provide human sign-off or automated semantic validation. Citation counts are unique IDs per run, not citation occurrences. Label comparisons use the proposed evaluation rubric in results.md, not an enforced application contract.', '',
  'Review checklist for each run: compare every factual statement with its source; preserve counterevidence; distinguish accepted email, delivered SMS, acknowledged access and attendance; check local event dates; check the label against the rubric; remove outcome/refund advice; judge whether the draft is a usable response. Record reviewer, corrections and actual elapsed review time separately. Literal escaped newlines are displayed as line breaks here only.', '',
];
for (const filename of readdirSync(directory).filter(name => name.endsWith('.json')).sort()) {
  const bytes = readFileSync(path.join(directory, filename));
  const saved = JSON.parse(bytes);
  const { order, run, draft, evidence } = saved;
  if (!expected[order]) throw new Error(`Unknown case in ${filename}`);
  if (!draft?.analysis || !Array.isArray(evidence)) throw new Error(`No reviewable draft/evidence in ${filename}; inspect the raw failed run.`);
  const byId = new Map(evidence.map(record => [record.id, record]));
  const retrieved = new Set(run.events.filter(event => event.type === 'tool_completed').flatMap(event => event.evidenceIds || []));
  const references = new Set([
    ...draft.analysis.evidenceIds,
    ...draft.analysis.findings.flatMap(finding => finding.evidenceIds),
    ...[...draft.content.matchAll(/(?<!\\)\[([^\[\]\r\n]+)\]/g)].map(match => match[1]),
  ]);
  const broken = [...references].filter(id => !byId.has(id));
  const notRetrieved = [...references].filter(id => !retrieved.has(id));
  const errors = [];
  if (run.status !== 'completed' || run.mode !== 'bedrock' || draft.method !== 'bedrock') errors.push('Not a completed Bedrock draft');
  if (draft.caseId !== saved.caseId || run.caseId !== saved.caseId) errors.push('Case mismatch');
  if (byId.size !== evidence.length) errors.push('Duplicate evidence IDs');
  if (evidence.some(record => record.caseId !== saved.caseId || record.provenance?.sourceMode !== 'synthetic')) errors.push('Evidence scope or provenance mismatch');
  if (broken.length) errors.push('Unresolved citations');
  if (notRetrieved.length) errors.push('Cited evidence absent from completed tool trace');
  const row = {
    file: filename, sha256: sha256(bytes), order, runId: run.id,
    mode: run.mode, modelId: run.modelId, evidenceRecords: evidence.length,
    retrievedRecordIds: retrieved.size, citedButNotRetrieved: notRetrieved,
    uniqueCitationIds: references.size, citationOccurrences: [...draft.content.matchAll(/(?<!\\)\[([^\[\]\r\n]+)\]/g)].length, brokenCitationIds: broken,
    expectedAssessment: expected[order], observedAssessment: draft.analysis.assessment,
    assessmentMatchesRubric: expected[order] === draft.analysis.assessment,
    gapCount: draft.analysis.gaps.length, structuralErrors: errors,
    backendSourceCommitVerified: false,
    investigatorArtifactRecorded: Boolean(saved.backendArtifacts?.before?.investigator),
  };
  rows.push(row);
  packet.push(`## ${order} — ${run.id}`, '',
    `Raw artifact: [${filename}](runs/${filename}). SHA-256: \`${row.sha256}\`.`, '',
    `Observed assessment: **${row.observedAssessment}**. Rubric: **${row.expectedAssessment}**. ${references.size} unique citations; ${broken.length} unresolved. Human reviewer: **not recorded**.`, '');
  for (const [title, value] of [['Summary', draft.analysis.summary], ['Response draft', draft.content], ['Recommendation', draft.analysis.recommendation]]) {
    packet.push(`### ${title}`, '', ...value.replaceAll('\\n', '\n').split('\n').map(line => line.trim() ? `> ${line.trimEnd()}` : '>'), '');
  }
  packet.push('### Findings and their cited sources', '');
  for (const finding of draft.analysis.findings) {
    packet.push(`**${finding.kind}: ${finding.title}**`, '', `> ${finding.detail}`, '');
    for (const id of finding.evidenceIds) {
      const source = byId.get(id);
      packet.push(source ? `- \`${id}\` → \`${source.provenance.originalSourceId}\`: ${source.content}` : `- **Unresolved:** \`${id}\``);
    }
    if (!finding.evidenceIds.length) packet.push('No cited source. Check that this is a gap, not an unsupported negative claim.');
    packet.push('');
  }
  packet.push('### Gaps as generated', '', ...draft.analysis.gaps.map(gap => `- ${gap}`), '', '### Full source appendix', '');
  for (const source of evidence) {
    packet.push(`**${source.title}** — \`${source.id}\``, '',
      `Original: \`${source.provenance.originalSourceId}\`; section: ${source.provenance.section}; recorded at: ${source.occurredAt}.`, '',
      `> ${source.content}`, '', '```json', JSON.stringify(source.provenance.fields, null, 2), '```', '',
      ...source.provenance.limitations.map(value => `- Source limitation: ${value}`), '');
  }
}
if (!rows.length) throw new Error('No saved runs found');
const summary = {
  scope: 'Offline structural audit; not a semantic accuracy score or human review',
  fixtureSha256: sha256(readFileSync('lib/ticket-demo.ts')),
  runs: rows.length,
  uniqueCitationIdsSummedAcrossRuns: rows.reduce((sum, row) => sum + row.uniqueCitationIds, 0),
  citationOccurrences: rows.reduce((sum, row) => sum + row.citationOccurrences, 0),
  brokenCitationIds: rows.flatMap(row => row.brokenCitationIds).length,
  assessmentMatchesRubric: rows.filter(row => row.assessmentMatchesRubric).length,
  rows,
};
writeFileSync('docs/evaluation/audit-summary.json', JSON.stringify(summary, null, 2) + '\n');
writeFileSync('docs/evaluation/review-packet.md', packet.join('\n').trimEnd() + '\n');
console.log(JSON.stringify({ runs: summary.runs, citations: summary.uniqueCitationIdsSummedAcrossRuns, broken: summary.brokenCitationIds, assessmentMatchesRubric: summary.assessmentMatchesRubric, structuralErrors: rows.flatMap(row => row.structuralErrors) }));
if (rows.some(row => row.structuralErrors.length)) process.exitCode = 1;
